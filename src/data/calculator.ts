// Пробел-разделитель разрядов без Intl — чтобы не ловить рассинхрон
// форматирования между сервером и клиентом при гидратации.
export function formatRub(value: number): string {
  return value.toString().replace(/\B(?=(\d{3})+(?!\d))/g, " ") + " ₽";
}
